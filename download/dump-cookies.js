// dump-cookies.js
// 通过 Chrome/Edge 的 DevTools 协议（CDP）把「所有站点」的 Cookie 一次性导出成
// yt-dlp / curl 通用的 Netscape 格式 cookies.txt
//
// 用法： node dump-cookies.js <输出文件> 
// 环境变量： CDP_PORT（默认 9222）

const fs = require('fs');

const PORT = process.env.CDP_PORT || '9222';
const OUT = process.argv[2] || 'cookies.txt';

function toNetscape(c) {
  const domain = c.domain || '';
  const includeSub = domain.startsWith('.') ? 'TRUE' : 'FALSE';
  const secure = c.secure ? 'TRUE' : 'FALSE';
  const expiry = typeof c.expires === 'number' && c.expires > 0 ? Math.floor(c.expires) : 0;
  const name = (c.name || '').replace(/[\t\r\n]/g, '');
  const value = String(c.value === undefined ? '' : c.value).replace(/[\r\n]+/g, ' ');
  const host = c.httpOnly ? '#HttpOnly_' + domain : domain;
  return [host, includeSub, c.path || '/', secure, expiry, name, value].join('\t');
}

async function getVersion(deadline) {
  for (;;) {
    try {
      const r = await fetch(`http://127.0.0.1:${PORT}/json/version`);
      if (r.ok) return await r.json();
    } catch (e) {
      /* 端口还没起来，继续等 */
    }
    if (Date.now() > deadline) throw new Error('CDP 端口没响应，浏览器可能没启动或调试端口被占用');
    await new Promise((res) => setTimeout(res, 500));
  }
}

(async () => {
  const v = await getVersion(Date.now() + 20000);
  console.log(`connected: ${v.Browser || 'Chromium'} / ${v['Protocol-Version'] || ''}`);

  const ws = new WebSocket(v.webSocketDebuggerUrl);
  const done = new Promise((resolve, reject) => {
    ws.addEventListener('open', () => {
      ws.send(JSON.stringify({ id: 1, method: 'Storage.getCookies', params: {} }));
    });
    ws.addEventListener('message', (ev) => {
      let msg;
      try { msg = JSON.parse(ev.data); } catch { return; }
      if (msg.id !== 1) return;
      if (msg.error) return reject(new Error('CDP error: ' + JSON.stringify(msg.error)));
      resolve(msg.result && msg.result.cookies ? msg.result.cookies : []);
    });
    ws.addEventListener('error', () => reject(new Error('WebSocket 连接失败')));
  });

  const cookies = await done;

  const seen = new Set();
  const lines = [];
  for (const c of cookies) {
    const line = toNetscape(c);
    if (seen.has(line)) continue;
    seen.add(line);
    lines.push(line);
  }

  const domainCount = new Set(cookies.map((c) => (c.domain || '').replace(/^\./, ''))).size;
  const header =
    '# Netscape HTTP Cookie File\n' +
    `# generated by dump-cookies.js on ${new Date().toISOString()}\n` +
    `# cookies: ${lines.length}, domains: ${domainCount}\n\n`;

  fs.writeFileSync(OUT, header + lines.join('\n') + '\n', 'utf8');
  console.log(`written: ${lines.length} cookies from ${domainCount} domains -> ${OUT}`);

  try {
    ws.send(JSON.stringify({ id: 2, method: 'Browser.close' }));
  } catch (e) { /* 忽略 */ }
  setTimeout(() => process.exit(0), 500);
})().catch((e) => {
  console.error('FAILED: ' + e.message);
  process.exit(1);
});
